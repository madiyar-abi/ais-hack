import { NextResponse } from 'next/server';
import { GoogleGenerativeAI } from '@google/generative-ai';

// Инициализация Gemini
const apiKey = process.env.GEMINI_API_KEY!;
const genAI = new GoogleGenerativeAI(apiKey);

// Симуляция RAG базы (базовые знания ИИ о приказах, которые мы используем как System Prompt Context)
const RAG_CONTEXT = `
ТЫ ЭКСПЕРТ-ЮРИСТ ПО ОБРАЗОВАТЕЛЬНОМУ ЗАКОНОДАТЕЛЬСТВУ РЕСПУБЛИКИ КАЗАХСТАН (БЮРОКРАТИЧЕСКИЙ RAG).
В твое векторное хранилище загружены следующие документы:
1. Приказ №76 (Нормы педагогической нагрузки, правила составления расписания, допустимое количество уроков, дежурства).
2. Приказ №110 (Правила проведения занятий, аттестация, этика, взаимодействие с родителями).
3. Приказ №130 (Правила оценивания учебных достижений обучающихся, формативное и суммативное оценивание (СОР/СОЧ), сроки выставления оценок).

Если пользователь просит проверить расписание/задачу на соответствие, ты должен:
- Строго указать, ЕСТЬ ЛИ нарушения этих приказов.
- Если есть, привести выдержку с указанием номера приказа.
- Если нарушений нет, так и сказать.
Тон: официальный, но понятный директору школы. Не выдумывай номера пунктов, опирайся на логику стандартных образовательных норм РК (например: запрет на более 3-4 сложных предметов подряд, перерыв между уроками, лимит СОР/СОЧ в один день не более 3-х).

Если пользователь просит перевести приказ в чек-лист (translation mode), ты должен:
- Игнорировать юридическую воду и "птичий язык".
- Выдать четкий, пошаговый Bullet-point список (или чек-лист) для простой рассылки учителям в WhatsApp.
- Максимально упростить язык.
Тон: дружелюбный, прямой, инструктивный.
`;

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const { action, text } = body;

    if (!text) {
      return NextResponse.json({ error: 'Текст не предоставлен' }, { status: 400 });
    }

    const model = genAI.getGenerativeModel({ model: "gemini-2.5-flash" });

    if (action === 'generate') {
      const { history } = body;
      // Конвертируем историю под формат Gemini (role: 'user' | 'model', parts: [{text}])
      const formattedHistory = (history || []).map((msg: any) => ({
        role: msg.role === 'user' ? 'user' : 'model',
        parts: [{ text: msg.content }]
      }));
      
      const chat = model.startChat({
        history: [
          { role: 'user', parts: [{ text: RAG_CONTEXT }] },
          { role: 'model', parts: [{ text: 'Понял. Я готов работать как генератор экспертных документов и приказов в диалоговом режиме.' }] },
          ...formattedHistory
        ]
      });

      const promptUser = `
ПОЛЬЗОВАТЕЛЬ ПИШЕТ:
"${text}"

ИНСТРУКЦИЯ К ДЕЙСТВИЮ:
Если пользователь только что попросил составить документ/приказ, но не дал деталей (ФИО, классы, даты, конкретика нарушения/задачи) - ЗАДАЙ ЕМУ УТОЧНЯЮЩИЕ ВОПРОСЫ в формате нумерованного списка.
Если в тексте (или в истории) достаточно деталей, СГЕНЕРИРУЙ ГОТОВЫЙ ОФИЦИАЛЬНЫЙ ПРИКАЗ, используя формальный язык Приказов 76, 110 или 130. Оформи в четкий Markdown с гербом (просто текстом), заголовком, преамбулой и пунктами.
Будь краток и хирургически точен.
      `;
      
      const result = await chat.sendMessage(promptUser);
      return NextResponse.json({ result: result.response.text() });
    }

    let prompt = "";
    if (action === 'check') {
      prompt = `
${RAG_CONTEXT}

ЗАДАЧА ОТ ПОЛЬЗОВАТЕЛЯ (ПРОВЕРКА НА НАРУШЕНИЯ):
Пожалуйста, проанализируй следующий текст директора или кусок расписания. 
Укажи, есть ли в нем нарушения Приказов №76, 110, 130. Разложи по полочкам:
1. Выявленные риски/нарушения.
2. Что именно нарушено (по какому приказу).
3. Рекомендация по исправлению.

ТЕКСТ:
"${text}"
      `;
    } else if (action === 'translate') {
      prompt = `
${RAG_CONTEXT}

ЗАДАЧА ОТ ПОЛЬЗОВАТЕЛЯ (ПЕРЕВОД В ЧЕК-ЛИСТ ДЛЯ УЧИТЕЛЕЙ):
Пожалуйста, возьми следующий бюрократический текст из приказа/распоряжения и перепиши его в виде короткого, мотивирующего чек-листа в WhatsApp-стиле для учителей. Убери всю воду.

ТЕКСТ:
"${text}"
      `;
    } else {
       return NextResponse.json({ error: 'Неизвестное действие' }, { status: 400 });
    }

    const result = await model.generateContent(prompt);
    const responseText = result.response.text();

    return NextResponse.json({ result: responseText });
  } catch (error: any) {
    console.error('Ошибка в Bureaucratic RAG API:', error);
    return NextResponse.json(
      { error: 'Внутренняя ошибка сервера: ' + error.message },
      { status: 500 }
    );
  }
}
